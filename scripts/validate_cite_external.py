#!/usr/bin/env python3
"""Run the official OGC Processes 1.0 CITE suite against an existing API using Docker.

Standalone: Python 3.12+ standard library and Docker only. No Raster Processes API
imports, application deployment, Compose configuration or baseline comparison.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os

# Fixed executable/argument vectors; no shell or user-supplied executable.
import subprocess  # nosec B404
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import urlsplit
from uuid import uuid4

# Only native reports generated by the pinned official test image are parsed.
from xml.etree import ElementTree as ET  # nosec B405
from zipfile import ZIP_DEFLATED, ZipFile, is_zipfile

IMAGE = (
    "ogccite/ets-ogcapi-processes10:1.3-teamengine-6.0.0-RC2"
    "@sha256:8879e2d608e654d1f68aa94a2fd3b9bb1376f400737a2732ed32915a8e5211e8"
)
SUITE = "ogcapi-processes-1.0-1.3"
CLASSPATH = (
    "/usr/local/tomcat/webapps/teamengine/WEB-INF/classes:"
    "/usr/local/tomcat/webapps/teamengine/WEB-INF/lib/*:/usr/local/tomcat/lib/*"
)
CONTROLLER = "org.opengis.cite.ogcapiprocesses10.TestNGController"


class InfrastructureError(RuntimeError):
    """The validator could not complete execution, reporting or cleanup."""


def command(arguments, *, log, timeout):
    """Retain each Docker invocation's output, including failed or timed-out runs."""
    try:
        with log.open("w") as stream:
            result = subprocess.run(  # nosec B603
                arguments, stdout=stream, stderr=subprocess.STDOUT, timeout=timeout, check=False
            )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise InfrastructureError(f"{error}; see {log}") from error
    if result.returncode:
        raise InfrastructureError(f"Docker exited {result.returncode}; see {log}")


def base_url(value):
    try:
        parsed = urlsplit(value)
        valid = (
            parsed.scheme in {"http", "https"}
            and parsed.hostname
            and parsed.username is None
            and parsed.password is None
            and not parsed.query
            and not parsed.fragment
            and not any(character.isspace() or ord(character) < 32 for character in value)
        )
        _ = parsed.port  # reject malformed/out-of-range ports
    except ValueError:
        valid = False
    if not valid:
        raise argparse.ArgumentTypeError("Use an absolute HTTP(S) API root URL without credentials, query or fragment")
    return value.rstrip("/")


def positive_integer(value):
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("Must be greater than zero")
    return number


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", required=True, type=base_url, help="API landing-page URL, reachable from Docker")
    parser.add_argument(
        "--echo-process", required=True, help="ID of a compatible echo process already on the target API"
    )
    parser.add_argument(
        "--output-dir", type=Path, default=Path("runtime-data/cite-external"), help="Parent of unique run directories"
    )
    parser.add_argument("--network", default="bridge", help="Existing Docker network, or 'host' for host networking")
    parser.add_argument(
        "--timeout", type=positive_integer, default=900, help="Test execution timeout in seconds (default: 900)"
    )
    return parser.parse_args(argv)


def read_results(path):
    root = ET.parse(path).getroot()  # nosec B314
    if root.tag != "testng-results" or root.find("suite") is None:
        raise InfrastructureError("Not a native TestNG report")
    if root.find("suite").get("name") != SUITE:
        raise InfrastructureError("Unexpected suite/version in native report")
    cases, configuration_failures = [], []
    for group in root.findall("./suite/test"):
        for test_class in group.findall("class"):
            for method in test_class.findall("test-method"):
                case = {
                    "group": group.get("name"),
                    "class": test_class.get("name"),
                    "name": method.get("name"),
                    "status": method.get("status"),
                    "requirement": method.get("description", "").strip(),
                    "message": (method.findtext("exception/message") or "").strip(),
                }
                if method.get("is-config") == "true":
                    if case["status"] == "FAIL":
                        configuration_failures.append(case)
                    continue
                if not all(case[field] for field in ("group", "class", "name")):
                    raise InfrastructureError("Native test case is missing its identity")
                if case["status"] not in {"PASS", "FAIL", "SKIP"}:
                    raise InfrastructureError("Unexpected native test status")
                cases.append(case)
    if not cases:
        raise InfrastructureError("No executable test cases in native report")
    counts = Counter(case["status"] for case in cases)
    for field, status in (("passed", "PASS"), ("failed", "FAIL"), ("skipped", "SKIP")):
        if int(root.get(field, "-1")) != counts[status]:
            raise InfrastructureError(f"Native {field} total does not match individual tests")
    if not counts["PASS"] and not counts["FAIL"]:
        raise InfrastructureError("All test cases were skipped; no conformance result can be claimed")
    return {
        "suite": SUITE,
        "counts": {status: counts[status] for status in ("PASS", "FAIL", "SKIP")},
        "configurationFailures": configuration_failures,
        "cases": cases,
    }


def collect_reports(directory):
    reports = list((directory / "reports").rglob("testng-results.xml"))
    if len(reports) != 1:
        raise InfrastructureError(f"Expected one native TestNG report; found {len(reports)}")
    native = reports[0]
    summary = read_results(native)
    result = native.parent / "result"
    artifacts = {
        "nativeXml": native,
        "nativeEarl": native.parent / "earl-results.rdf",
        "nativeHtmlArchive": native.parent / "result.zip",
        "officialHtmlReport": result / "index.html",
    }
    for path in artifacts.values():
        if not path.is_file() or not path.stat().st_size:
            raise InfrastructureError(f"Missing or empty official report: {path}")
    if not is_zipfile(artifacts["nativeHtmlArchive"]):
        raise InfrastructureError("Native HTML archive is not a valid ZIP")
    # The pinned engine flattens asset directories in its ZIP. Keep that ZIP;
    # package the unchanged official HTML/assets separately with working paths.
    artifacts["officialHtmlArchive"] = directory / "official-report.zip"
    with ZipFile(artifacts["officialHtmlArchive"], "w", compression=ZIP_DEFLATED) as archive:
        for path in sorted(result.rglob("*")):
            if path.is_file():
                archive.write(path, path.relative_to(result))
    (directory / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    return summary, {key: path.relative_to(directory).as_posix() for key, path in artifacts.items()}


def run(args):
    name = "ogc-processes-cite-" + uuid4().hex[:12]
    directory = args.output_dir.resolve() / name
    directory.mkdir(parents=True)
    (directory / "reports").mkdir()
    parameters = {
        "iut": args.base_url,
        "echoprocessid": args.echo_process,
        "testallprocesses": "on",
        "processtestlimit": "0",
        "acceptMediaType": "application/zip",
    }
    properties = ET.Element("properties")
    for key, value in parameters.items():
        ET.SubElement(properties, "entry", key=key).text = value
    ET.ElementTree(properties).write(directory / "test-run-props.xml", encoding="utf-8", xml_declaration=True)
    metadata = {
        "image": IMAGE,
        "suite": SUITE,
        "teamengineVersion": "6.0.0-RC2",
        "started": datetime.now(UTC).isoformat(),
        "parameters": parameters,
        "network": args.network,
        "timeoutSeconds": args.timeout,
        "container": name,
        "runnerSha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    print(f"Target: {args.base_url}\nReports: {directory}", flush=True)
    status = 2
    created = False
    try:
        command(
            [
                "docker",
                "create",
                "--name",
                name,
                "--network",
                args.network,
                "--user",
                f"{os.getuid()}:{os.getgid()}",
                "--volume",
                f"{directory}:/run:ro",
                "--volume",
                f"{directory / 'reports'}:/reports",
                "--entrypoint",
                "java",
                IMAGE,
                "-Xmx1024m",
                "-Duser.home=/tmp",
                "-cp",
                CLASSPATH,
                CONTROLLER,
                "-o",
                "/reports",
                "/run/test-run-props.xml",
            ],
            log=directory / "container-create.log",
            timeout=300,
        )
        created = True
        command(["docker", "start", "--attach", name], log=directory / "cite-cli.log", timeout=args.timeout)
        summary, artifacts = collect_reports(directory)
        metadata.update(artifacts)
        print(f"Official HTML: {directory / artifacts['officialHtmlReport']}", flush=True)
        print(f"Shareable report: {directory / artifacts['officialHtmlArchive']}", flush=True)
        print(f"CITE: {summary['counts']}", flush=True)
        for case in summary["cases"]:
            if case["status"] == "FAIL":
                print(f"FAIL {case['name']}: {case['message']}", flush=True)
        status = 1 if summary["counts"]["FAIL"] or summary["configurationFailures"] else 0
    except KeyboardInterrupt:
        print("Interrupted; cleaning up the validator container.", file=sys.stderr)
        status = 130
    except (InfrastructureError, OSError, ValueError, ET.ParseError) as error:
        print(f"INFRASTRUCTURE ERROR: {error}", file=sys.stderr)
        (directory / "infrastructure-error.txt").write_text(str(error) + "\n")
    finally:
        if created:
            try:
                command(["docker", "rm", "--force", name], log=directory / "cleanup.log", timeout=60)
            except InfrastructureError as error:
                print(f"INFRASTRUCTURE ERROR during cleanup: {error}", file=sys.stderr)
                metadata["cleanupError"] = str(error)
                status = 2
        metadata["finished"] = datetime.now(UTC).isoformat()
        metadata["exitCode"] = status
        (directory / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    return status


def main(argv=None):
    args = parse_args(argv)
    try:
        return run(args)
    except KeyboardInterrupt:
        print("Interrupted; validator container cleanup attempted.", file=sys.stderr)
        return 130
    except OSError as error:
        print(f"INFRASTRUCTURE ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
